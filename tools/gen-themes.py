#!/usr/bin/env python3
"""Generate theme files from themes/palettes/palettes.json.

Outputs (committed, so the image build needs no Python step):
  system_files/usr/share/color-schemes/OldNet<Id>.colors   KDE color schemes
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PALETTES = ROOT / "themes" / "palettes" / "palettes.json"
COLOR_SCHEMES = ROOT / "system_files" / "usr" / "share" / "color-schemes"


def rgb(hex_color):
    h = hex_color.lstrip("#")
    return ",".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))


def color_group(p, background, alternate, foreground=None, inactive=None):
    fg = foreground or p["text"]
    return {
        "BackgroundAlternate": alternate,
        "BackgroundNormal": background,
        "DecorationFocus": p["focus"],
        "DecorationHover": p["hover"],
        "ForegroundActive": p["accent"],
        "ForegroundInactive": inactive or p["muted"],
        "ForegroundLink": p["link"],
        "ForegroundNegative": p["negative"],
        "ForegroundNeutral": p["neutral"],
        "ForegroundNormal": fg,
        "ForegroundPositive": p["positive"],
        "ForegroundVisited": p["visited"],
    }


def kde_colors(scheme_id, p):
    sel = color_group(p, p["selection"], p["focus"], p["selectionText"], p["selectionText"])
    # Text on a bright selection must stay dark, so link/state colours follow it.
    for key in ("ForegroundActive", "ForegroundLink", "ForegroundVisited"):
        sel[key] = p["selectionText"]
    sections = {
        "ColorEffects:Disabled": {
            "Color": rgb(p["surface"]), "ColorAmount": "0", "ColorEffect": "0",
            "ContrastAmount": "0.65", "ContrastEffect": "1",
            "IntensityAmount": "0.1", "IntensityEffect": "2",
        },
        "ColorEffects:Inactive": {
            "ChangeSelectionColor": "true", "Color": rgb(p["surface"]),
            "ColorAmount": "0.025", "ColorEffect": "2", "ContrastAmount": "0.1",
            "ContrastEffect": "2", "Enable": "false",
            "IntensityAmount": "0", "IntensityEffect": "0",
        },
        "Colors:Button": color_group(p, p["raised"], p["alt"]),
        "Colors:Complementary": color_group(p, p["complementary"], p["surface"],
                                            p["complementaryText"]),
        "Colors:Header": color_group(p, p["surface"], p["alt"]),
        "Colors:Header][Inactive": color_group(p, p["bg"], p["alt"]),
        "Colors:Selection": sel,
        "Colors:Tooltip": color_group(p, p["tooltip"], p["surface"]),
        "Colors:View": color_group(p, p["bg"] if p["dark"] else p["surface"], p["alt"]),
        "Colors:Window": color_group(p, p["surface"] if p["dark"] else p["bg"], p["alt"]),
        "General": {
            "ColorScheme": f"OldNet{scheme_id}",
            "Name": p["name"],
            "accentActiveTitlebar": "false",
            "shadeSortColumn": "true",
        },
        "KDE": {"contrast": "4"},
        "WM": {
            "activeBackground": p["titleActive"],
            "activeBlend": p["accent"],
            "activeForeground": p["titleActiveText"],
            "inactiveBackground": p["titleInactive"],
            "inactiveBlend": p["titleInactive"],
            "inactiveForeground": p["titleInactiveText"],
        },
    }
    out = ["# Generated by tools/gen-themes.py from themes/palettes/palettes.json - do not edit"]
    for name, values in sections.items():
        out.append(f"\n[{name}]")
        for key, value in values.items():
            out.append(f"{key}={rgb(value) if value.startswith('#') else value}")
    return "\n".join(out) + "\n"


def main():
    palettes = json.loads(PALETTES.read_text(encoding="utf-8"))["palettes"]
    COLOR_SCHEMES.mkdir(parents=True, exist_ok=True)
    for scheme_id, p in palettes.items():
        target = COLOR_SCHEMES / f"OldNet{scheme_id}.colors"
        target.write_text(kde_colors(scheme_id, p), encoding="utf-8", newline="\n")
        print(f"wrote {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
